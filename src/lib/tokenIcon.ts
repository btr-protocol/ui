/** Labels drawn with another symbol's mark: aggregates as BTR, on-chain spellings of an asset as the asset. */
const ALIAS: Record<string, string> = { PROTOCOL: 'BTR', POOL: 'BTR', USDT0: 'USDT', XAUT0: 'XAUT', WMON: 'MON', QQQB: 'QQQ' };

/** URL of a token's mark by ticker, or `undefined` when the kit carries none. */
export function tokenIcon(symbol: string): string | undefined {
  const raw = canonicalTokenSymbol(symbol);
  return TOKENS[(ALIAS[raw] ?? raw).toLowerCase()];
}
